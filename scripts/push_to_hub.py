"""Publish the fine-tuned embedding model to the Hugging Face Hub with an honest model card.

The evaluation table in the card is read from results/retrieval_eval.json, so the numbers are never typed by hand.

    hf auth login
    python -m scripts.push_to_hub --repo-id YOUR-HF-USERNAME/minilm-fastapi-docs-retrieval
"""

import argparse
import json
from pathlib import Path

BASE_MODEL = "sentence-transformers/all-MiniLM-L6-v2"
FT_KEY = "models/embedding-ft"
REPO_URL = "https://github.com/Sushmitha2707/multimodal-rag-copilot"

CARD = """---
license: apache-2.0
base_model: {base}
library_name: sentence-transformers
pipeline_tag: sentence-similarity
tags:
  - sentence-transformers
  - embeddings
  - retrieval
  - rag
---

# {name}

`{base}` fine-tuned for question-to-passage retrieval over FastAPI documentation.
It maps text to 384-dimensional vectors and was built for the RAG pipeline in
[multimodal-rag-copilot]({repo_url}).

## Training

- **Data:** {n_pairs} (question, passage) pairs. Passages are chunks of the FastAPI tutorial
  documentation (MIT licensed). The questions were generated by an LLM (Gemini) from each passage.
- **Method:** `MultipleNegativesRankingLoss` (other passages in a batch act as negatives), 3 epochs,
  batch size 32, learning rate 2e-5, trained with `sentence-transformers` on PyTorch.
- **Split:** documents were split by file into train and held-out sets, so the held-out
  documents were never seen in training.

## Evaluation

Held-out documents: {n_queries} synthetic queries searched over {n_passages} passages.

| Model | Recall@1 | Recall@3 | Recall@5 | MRR@10 |
|---|---|---|---|---|
| {base} (base) | {b1} | {b3} | {b5} | {bm} |
| This model | {f1} | {f3} | {f5} | {fm} |

## Usage

```python
from sentence_transformers import SentenceTransformer

model = SentenceTransformer("{repo_id}")
embeddings = model.encode(["How do I add a prefix to a router in FastAPI?"], normalize_embeddings=True)
```

## Limitations

- Tuned for one domain (FastAPI documentation); gains are not expected to transfer to other domains.
- Evaluated on LLM-generated queries from the same documentation, not on real user queries.
- Small evaluation pool and a single training run, so no confidence intervals.
"""


def build_card(results: dict, repo_id: str, n_pairs: str, n_queries: str, n_passages: str) -> str:
    b, f = results[BASE_MODEL], results[FT_KEY]
    fmt = "{:.3f}".format
    return CARD.format(
        base=BASE_MODEL,
        name=repo_id.split("/")[-1],
        repo_url=REPO_URL,
        repo_id=repo_id,
        n_pairs=n_pairs,
        n_queries=n_queries,
        n_passages=n_passages,
        b1=fmt(b["recall@1"]),
        b3=fmt(b["recall@3"]),
        b5=fmt(b["recall@5"]),
        bm=fmt(b["mrr@10"]),
        f1=fmt(f["recall@1"]),
        f3=fmt(f["recall@3"]),
        f5=fmt(f["recall@5"]),
        fm=fmt(f["mrr@10"]),
    )


def count_lines(path: str) -> str:
    p = Path(path)
    return str(sum(1 for _ in open(p, encoding="utf-8"))) if p.exists() else "N/A"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo-id", required=True, help="e.g. your-username/minilm-fastapi-docs-retrieval")
    ap.add_argument("--model-dir", default="models/embedding-ft")
    ap.add_argument("--results", default="results/retrieval_eval.json")
    ap.add_argument("--private", action="store_true", help="create a private repo (default: public)")
    args = ap.parse_args()

    if not Path(args.results).exists():
        raise SystemExit(f"{args.results} not found - run scripts.eval_retrieval first.")
    results = json.loads(Path(args.results).read_text())

    held = Path("data/pairs/heldout.jsonl")
    rows = [json.loads(line) for line in open(held, encoding="utf-8")] if held.exists() else []
    n_queries = str(len(rows)) if rows else "N/A"
    n_passages = str(len({r["passage"] for r in rows})) if rows else "N/A"

    card = build_card(results, args.repo_id, count_lines("data/pairs/train.jsonl"), n_queries, n_passages)
    Path(args.model_dir, "README.md").write_text(card, encoding="utf-8")
    print(f"Wrote model card to {args.model_dir}/README.md")

    from huggingface_hub import HfApi

    api = HfApi()
    api.create_repo(args.repo_id, exist_ok=True, private=args.private)
    api.upload_folder(
        folder_path=args.model_dir,
        repo_id=args.repo_id,
        commit_message="Fine-tuned MiniLM for FastAPI documentation retrieval",
        ignore_patterns=["checkpoint*", "checkpoints/*", "runs/*", "*.log"],
    )
    print(f"Done: https://huggingface.co/{args.repo_id}")


if __name__ == "__main__":
    main()
